// Generates src/types/database.ts from the SQL migrations, in the shape `supabase gen types` produces
// (Database['public']['Tables'][table]['Row' | 'Insert' | 'Update'] and Enums). It applies the
// migrations to an in-memory Postgres, so it needs no Supabase project.
// Once a project exists, `npx supabase gen types typescript --project-id <id>` gives the same result.
// Run: npm run db:types -w apps/web
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const migrations = path.join(root, 'supabase', 'migrations');
const out = path.join(root, 'apps', 'web', 'src', 'types', 'database.ts');

const db = new PGlite();
await db.exec(`
  create role anon nologin; create role authenticated nologin;
  create schema auth; create table auth.users (id uuid primary key);
  create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
  create schema storage;
  create table storage.buckets (id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
  create table storage.objects (id uuid primary key default gen_random_uuid(), bucket_id text, name text);
`);
for (const file of fs.readdirSync(migrations).sort()) await db.exec(fs.readFileSync(path.join(migrations, file), 'utf8'));

const enums = (await db.query(`
  select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`)).rows;

const columns = (await db.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable = 'YES' as nullable,
         c.column_default is not null as has_default, c.is_identity = 'YES' as identity
  from information_schema.columns c join information_schema.tables t
    on t.table_name = c.table_name and t.table_schema = c.table_schema
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.ordinal_position`)).rows;

// Functions callable through the API (granted to anon / authenticated)
const functions = (await db.query(`
  select p.proname as name, pg_get_function_arguments(p.oid) as args, pg_get_function_result(p.oid) as result
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.proname in ('is_admin', 'media_usage') order by 1`)).rows;

const SQL_TS = { text: 'string', uuid: 'string', boolean: 'boolean', bigint: 'number', integer: 'number', jsonb: 'Json' };
const sqlToTs = (type) => SQL_TS[type.trim()] ?? 'unknown';
/** "a text, b uuid" → { a: string; b: string } */
const argsTs = (args) =>
  args.trim() ? `{ ${args.split(',').map((a) => { const [n, ...t] = a.trim().split(/\s+/); return `${n}: ${sqlToTs(t.join(' '))}`; }).join('; ')} }` : 'Record<PropertyKey, never>';
/** "boolean" | "TABLE(a text, b bigint)" */
const resultTs = (result) => {
  const table = result.match(/^TABLE\((.*)\)$/);
  return table ? `${argsTs(table[1])}[]` : sqlToTs(result);
};

const enumNames = new Set(enums.map((e) => e.name));
function tsType(col) {
  if (col.data_type === 'USER-DEFINED' && enumNames.has(col.udt_name)) return `Database['public']['Enums']['${col.udt_name}']`;
  switch (col.udt_name) {
    case 'int2': case 'int4': case 'int8': case 'float4': case 'float8': case 'numeric': return 'number';
    case 'bool': return 'boolean';
    case 'json': case 'jsonb': return 'Json';
    case '_text': return 'string[]';
    default: return 'string';
  }
}

const tables = new Map();
for (const c of columns) {
  if (!tables.has(c.table_name)) tables.set(c.table_name, []);
  tables.get(c.table_name).push(c);
}

let ts = `// Generated by scripts/gen-types.mjs from supabase/migrations. Do not edit by hand.\n\n`;
ts += `export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n`;
ts += `export type Database = {\n  public: {\n    Tables: {\n`;
for (const [table, cols] of tables) {
  const row = cols.map((c) => `          ${c.column_name}: ${tsType(c)}${c.nullable ? ' | null' : ''};`).join('\n');
  const insert = cols
    .map((c) => `          ${c.column_name}${c.nullable || c.has_default || c.identity ? '?' : ''}: ${tsType(c)}${c.nullable ? ' | null' : ''};`)
    .join('\n');
  const update = cols.map((c) => `          ${c.column_name}?: ${tsType(c)}${c.nullable ? ' | null' : ''};`).join('\n');
  ts += `      ${table}: {\n        Row: {\n${row}\n        };\n        Insert: {\n${insert}\n        };\n        Update: {\n${update}\n        };\n        Relationships: [];\n      };\n`;
}
ts += `    };\n    Views: { [_ in never]: never };\n    Functions: {\n`;
for (const f of functions) ts += `      ${f.name}: { Args: ${argsTs(f.args)}; Returns: ${resultTs(f.result)} };\n`;
ts += `    };\n    Enums: {\n`;
for (const e of enums) ts += `      ${e.name}: ${e.labels.map((l) => `'${l}'`).join(' | ')};\n`;
ts += `    };\n    CompositeTypes: { [_ in never]: never };\n  };\n};\n\n`;
ts += `export type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row'];\n`;
ts += `export type TablesInsert<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Insert'];\n`;
ts += `export type TablesUpdate<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Update'];\n`;
ts += `export type Enums<T extends keyof Database['public']['Enums']> = Database['public']['Enums'][T];\n`;

fs.writeFileSync(out, ts);
console.log(`Wrote ${path.relative(root, out)}: ${tables.size} tables, ${enums.length} enums`);
