/**
 * Builds supabase/seed.sql: the content bundled with the site, ready to import into Supabase.
 *
 *   npm run db:seed:build -w apps/web
 *
 * Idempotent: every row has a stable id (md5 of a natural key) or a unique key, and every insert is
 * `on conflict do nothing`, so running the seed again never duplicates rows nor overwrites what the
 * club has since edited in the admin. Run it with scripts/db.mjs (or paste it in the SQL editor).
 */
import fs from 'node:fs';
import path from 'node:path';
import { mockNews } from '../src/lib/mock-data';
import { STAFF, STAFF_PHOTOS } from '../src/lib/staff';
import { BASKETBALL_FIXTURES, BASKETBALL_TICKETS, DISLOG_LEAGUE } from '../src/lib/basketball';
import { MATCH_NOTES } from '../src/lib/match-notes';
import { MENU, BAR_LINKS, type MenuNode, type NavLink } from '../src/lib/navigation-config';
import { FOOTER_CLUB_LINKS, FOOTER_SERVICE_LINKS, HOME_SECTION_KEYS, PARTNERS, SOCIAL_LINKS } from '../src/lib/site-defaults';
import { SECTION_PAGES } from '../src/lib/sections';
import { NewsCategoryEnum } from '../src/types/news';

const root = path.join(__dirname, '..', '..', '..');
const messages = Object.fromEntries(
  (['ar', 'fr', 'en'] as const).map((l) => [l, JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'messages', `${l}.json`), 'utf8'))]),
) as Record<'ar' | 'fr' | 'en', Record<string, Record<string, unknown>>>;

/** A message in the three languages: { ar, fr, en } */
function msg(namespace: string, key: string): Record<string, string> {
  const get = (obj: unknown, dotted: string) => dotted.split('.').reduce<unknown>((o, k) => (o as Record<string, unknown>)?.[k], obj);
  const out: Record<string, string> = {};
  for (const lang of ['ar', 'fr', 'en'] as const) {
    const v = get(messages[lang][namespace], key);
    if (typeof v === 'string') out[lang] = v;
  }
  return out;
}

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
/** Deterministic uuid from a natural key */
const id = (key: string) => `md5(${q(key)})::uuid`;

const sql: string[] = [
  '-- Generated by apps/web/scripts/seed.ts from the content bundled with the site. Safe to run again.',
  'begin;',
];
const insert = (table: string, row: Record<string, unknown>, conflict: string, raw: Record<string, string> = {}) => {
  const cols = [...Object.keys(row), ...Object.keys(raw)];
  const vals = [...Object.values(row).map(q), ...Object.values(raw)];
  sql.push(`insert into public.${table} (${cols.join(', ')}) values (${vals.join(', ')}) on conflict ${conflict} do nothing;`);
};

// ── Site settings ──
insert(
  'site_settings',
  {
    id: 1,
    club_name: msg('common', 'club_name'),
    logo_url: '/images/wydad-crest.svg',
    favicon_url: '/favicon.ico',
    social_links: SOCIAL_LINKS,
    partners: PARTNERS,
  },
  '(id)',
);

// ── Home sections ──
HOME_SECTION_KEYS.forEach((key, i) => insert('home_sections', { key, visible: true, sort: i * 10 }, '(key)'));

// ── Navigation ──
function navTree(menu: string, nodes: MenuNode[], parentKey: string | null) {
  nodes.forEach((n, i) => {
    const key = `nav:${menu}:${parentKey ?? ''}/${n.key}`;
    insert('navigation_items', { menu, label_key: n.key, href: n.href ?? null, sort: i * 10, visible: true }, '(id)', {
      id: id(key),
      parent_id: parentKey ? id(parentKey) : 'null',
    });
    if (n.children) navTree(menu, n.children, key);
  });
}
navTree('main', MENU, null);
const navLinks = (menu: string, links: NavLink[]) => navTree(menu, links.map(({ key, href }) => ({ key, href })), null);
navLinks('bar', BAR_LINKS);
navLinks('footer_club', FOOTER_CLUB_LINKS);
navLinks('footer_services', FOOTER_SERVICE_LINKS);

// ── News ──
NewsCategoryEnum.options.forEach((slug, i) => insert('categories', { slug, name: msg('news', slug), sort: i * 10 }, '(slug)'));
for (const a of mockNews) {
  insert(
    'news_articles',
    {
      legacy_id: a.id,
      slug: a.slug,
      title: a.title,
      excerpt: a.excerpt,
      body: a.body,
      sport: a.sport ?? 'football',
      cover_url: a.cover_image_url ?? null,
      cover_position: a.cover_position ?? null,
      cover_orientation: a.cover_orientation ?? null,
      match_id: a.match_id ?? null,
      author: a.author ?? null,
      read_time_minutes: a.read_time_minutes,
      status: 'published',
      published_at: a.published_at,
    },
    '(legacy_id)',
    { category_id: `(select id from public.categories where slug = ${q(a.category)})` },
  );
}

// ── Staff and its photo gallery ──
STAFF.forEach((m, i) =>
  insert(
    'staff_members',
    {
      squad: 'first_team',
      name: m.name,
      name_ar: m.name_ar ?? null,
      role: m.role,
      category: m.category,
      is_head: !!m.head,
      nationality: m.nationality ?? null,
      photo_url: m.photo ?? null,
      statement_url: m.statement ?? null,
      status: 'published',
      sort: i * 10,
    },
    '(id)',
    { id: id(`staff:first_team:${m.name}`) },
  ),
);

function gallery(slug: string, title: Record<string, string>, description: Record<string, string> | null, images: { src: string; width?: number; height?: number }[]) {
  insert('galleries', { slug, title, description, cover_url: images[0]?.src ?? null, status: 'published' }, '(slug)');
  images.forEach((img, i) =>
    insert('gallery_items', { image_url: img.src, width: img.width ?? null, height: img.height ?? null, sort: i * 10 }, '(gallery_id, image_url)', {
      gallery_id: `(select id from public.galleries where slug = ${q(slug)})`,
    }),
  );
}
gallery('staff-first-team', msg('football', 'staff_gallery_title'), msg('football', 'staff_gallery_text'), STAFF_PHOTOS);
const swimming = SECTION_PAGES.find((s) => s.key === 'swimming');
if (swimming?.gallery) {
  gallery('swimming-archives', msg('sections', 'swimming.gallery_title'), msg('sections', 'swimming.gallery_text'), swimming.gallery.images.map((src) => ({ src })));
}

// ── Basketball fixtures ──
insert('competitions', { slug: DISLOG_LEAGUE.id, sport: 'basketball', name: DISLOG_LEAGUE.name, short_name: DISLOG_LEAGUE.short_name, season: '2026-27' }, '(slug)');
